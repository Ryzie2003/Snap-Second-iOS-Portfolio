    /// User turned backup ON → create a new snapshot and make it active.
    func startNewBackupSession(name: String? = nil) async throws {
        cancelInitialBackupIfRunning()
        // If a session is already active (restored or just created), reuse it.
        if let active = self.activeBackupId {
            print("ℹ️ Reusing existing active backup \(active)")
            await self.syncActiveJournalSnapshotIfNeeded()
            publish(.init(state: .scanning, total: 0, done: 0, currentName: nil))
            startInitialBackup(forceRestart: true)
            return
        }

        guard let uid else { throw BackupError.missingUser }

        // Before creating a new one, see if there’s already an 'active' in Firestore (e.g., from another device)
        let col = db.collection("users").document(uid).collection("backups")
        if let existing = try? await col.whereField("status", isEqualTo: "active").limit(to: 1).getDocuments(),
           let existingId = existing.documents.first?.documentID {
            self.activeBackupId = existingId
            defaults.set(existingId, forKey: activeIdKey)
            // ⬇️ initialize metadata writer for incremental events
            let colRef = try self.clipsCollection(existingId)
            self.metadataWriter = FirestoreMetadataWriter(collection: colRef)
            await self.syncActiveJournalSnapshotIfNeeded()

            print("ℹ️ Found existing active backup in Firestore \(existingId); reusing")
            publish(.init(state: .scanning, total: 0, done: 0, currentName: nil))
            startInitialBackup(forceRestart: false)
            return
        }

        let backupId = UUID().uuidString

        let doc = try backupDoc(backupId)
        try await doc.setData([
            "createdAt": FieldValue.serverTimestamp(),
            "updatedAt": FieldValue.serverTimestamp(),
            "name": name ?? "Backup \(Date().formatted(date: .abbreviated, time: .shortened))",
            "status": "active",
            "deviceName": UIDevice.current.name
        ], merge: true)

        // Best-effort: close any other 'active' backups for this user so only this one remains active
        Task {
            do {
                let actives = try await col.whereField("status", isEqualTo: "active").getDocuments()
                for d in actives.documents where d.documentID != backupId {
                    try await col.document(d.documentID).setData([
                        "status": "completed",
                        "updatedAt": FieldValue.serverTimestamp()
                    ], merge: true)
                }
            } catch {
                print("⚠️ Could not complete stray active backups: \(error.localizedDescription)")
            }
        }

        self.activeBackupId = backupId
        defaults.set(backupId, forKey: activeIdKey)

        // ⬇️ initialize metadata writer for incremental events
        let colRef = try self.clipsCollection(backupId)
        self.metadataWriter = FirestoreMetadataWriter(collection: colRef)
        await self.syncActiveJournalSnapshotIfNeeded()

        publish(.init(state: .scanning, total: 0, done: 0, currentName: nil))
        // Kick off the full scan into this backup
        startInitialBackup(forceRestart: true)

    }

    /// User turned backup OFF → mark snapshot complete; stop incremental writes.
    func endBackupSession() async {

        isShuttingDown = true
        for t in uploadTasks { t.cancel() }
        uploadTasks.removeAll()
        cancelInitialBackupIfRunning()

        guard let backupId = activeBackupId else {
            isShuttingDown = false
            return
        }
        do {
            try await backupDoc(backupId).setData([
                "status": "completed",
                "updatedAt": FieldValue.serverTimestamp()
            ], merge: true)
        } catch {
            print("⚠️ Failed to mark backup completed: \(error)")
        }
        publish(.init(state: .finishing, total: 0, done: 0, currentName: nil))
        self.activeBackupId = nil
        defaults.removeObject(forKey: activeIdKey)

        // Flush and clear writer upon ending the session
        await metadataWriter?.flushNow()
        metadataWriter = nil

        publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
        isShuttingDown = false

    }


    // MARK: - Initial full backup
    func initialFullBackup() async {
        // --- Guards (don’t show “Scanning…” unless a session is active)
        guard let enumerator else { return }
        guard self.uid != nil else { return }
        guard let backupId = self.activeBackupId else {
            print("ℹ️ No active backup; skipping initialFullBackup.")
            publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
            return
        }

        // Ensure a writer is ready even if we didn’t come through startNewBackupSession()
        if self.metadataWriter == nil {
            do {
                let colRef = try self.clipsCollection(backupId)
                self.metadataWriter = FirestoreMetadataWriter(collection: colRef)
            } catch {
                print("⚠️ Unable to initialize metadata writer: \(error.localizedDescription)")
            }
        }


        // Safe to tell UI we're scanning now
        publish(.init(state: .scanning, total: 0, done: 0, currentName: nil))

        // (optional) trace one run
        let runTag = UUID().uuidString.prefix(6)
        print("▶️ initialFullBackup start [\(runTag)]")
        defer { print("⏹️ initialFullBackup end   [\(runTag)]") }

        // … after enumeration …
        if Task.isCancelled || isShuttingDown || self.activeBackupId != backupId {
            print("ℹ️ initialFullBackup aborted before hashing")
            publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
            return
        }

        // … after hashing / preflight …
        if Task.isCancelled || isShuttingDown || self.activeBackupId != backupId {
            print("ℹ️ initialFullBackup aborted before uploads")
            publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
            return
        }


        // --- 1) Enumerate, but read ONLY size now (no hashing yet)
        let base = await MainActor.run { enumerator() }

        // A light record to avoid hashing early
        struct Lite {
            let id: String
            let url: URL
            let bytes: Int64
            let createdAt: Date
            let journalId: String?
            let ext: String
        }

        var lite: [Lite] = []
        lite.reserveCapacity(base.count)

        for item in base {
            do {
                let attrs = try FileManager.default.attributesOfItem(atPath: item.fileURL.path)
                let bytes = (attrs[.size] as? NSNumber)?.int64Value ?? 0
                lite.append(.init(id: item.id,
                                  url: item.fileURL,
                                  bytes: bytes,
                                  createdAt: item.createdAt,
                                  journalId: item.journalId,
                                  ext: item.ext))
            } catch {
                print("⚠️ Skipping \(item.fileURL.lastPathComponent): \(error)")
            }
        }



        // --- 2) Pre-flight (batched Firestore): decide what needs work
        var toHashOrUpload: [Lite] = []
        do {
            let coll = try self.clipsCollection(backupId)
            let snapshot = try await coll.getDocuments()   // single roundtrip
            var remote: [String: (sha: String, bytes: Int64, deleted: Bool)] = [:]
            for d in snapshot.documents {
                let data = d.data()
                let sha = data["sha256"] as? String ?? ""
                let bytes = Self.int64Value(data["bytes"]) ?? -1
                let deleted = (data["deleted"] as? Bool) ?? false
                remote[d.documentID] = (sha, bytes, deleted)
            }

            for l in lite {
                if let r = remote[l.id], r.deleted == false {
                    // if bytes differ, we definitely need to upload; don't hash yet
                    if r.bytes != l.bytes {
                        toHashOrUpload.append(l)
                        continue
                    }
                    // bytes equal → we must hash THIS ONE to confirm
                    toHashOrUpload.append(l)
                } else {
                    // no remote doc → needs upload
                    toHashOrUpload.append(l)
                }
            }
        } catch {
            print("❌ initialFullBackup: preflight snapshot failed: \(error.localizedDescription)")
            // If preflight fails (offline), assume all need upload
            toHashOrUpload = lite
        }

        // we will hash only these candidates
        let prepareTotal = toHashOrUpload.count
        publish(.init(state: .preparing, total: prepareTotal, done: 0, currentName: nil))
        var prepareDone = 0


        // --- 3) Hash only the clips that might change / need upload (parallel, capped)
        nonisolated func makeLocalClip(from l: Lite) async throws -> LocalClip {
            try await self.prepareLocalClip(id: l.id,
                                            url: l.url,
                                            createdAt: l.createdAt,
                                            journalId: l.journalId,
                                            ext: l.ext)
        }

        var prepared: [LocalClip] = []
        prepared.reserveCapacity(toHashOrUpload.count)

        if toHashOrUpload.isEmpty {
            // nothing to hash or upload
            publish(.init(state: .finishing, total: 0, done: 0, currentName: nil))
            publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
            print("✅ Initial backup: library already up to date.")
            return
        }

        let hashGate = Gate(maxParallelHashes)
        await withTaskGroup(of: LocalClip?.self) { group in
            for l in toHashOrUpload {
                group.addTask {
                    await hashGate.acquire()
                    defer { Task { await hashGate.release() } }
                    do {
                        let clip = try await makeLocalClip(from: l)
                        // progress for hashing
                        await MainActor.run {
                            prepareDone += 1
                            self.publish(.init(state: .preparing,
                                               total: prepareTotal,
                                               done: prepareDone,
                                               currentName: l.id))
                        }
                        return clip
                    } catch {
                        print("⚠️ Hashing failed for \(l.id): \(error.localizedDescription)")
                        await MainActor.run {
                            prepareDone += 1
                            self.publish(.init(state: .preparing,
                                               total: prepareTotal,
                                               done: prepareDone,
                                               currentName: l.id))
                        }
                        return nil
                    }
                }
            }
            for await maybe in group {
                if let clip = maybe { prepared.append(clip) }
            }
        }


        // If preflight snapshot was available, skip ones that are actually up-to-date
        var toUpload: [LocalClip] = []
        do {
            let coll = try self.clipsCollection(backupId)
            let snapshot = try await coll.getDocuments()
            var remote: [String: (sha: String, bytes: Int64, deleted: Bool)] = [:]
            for d in snapshot.documents {
                let data = d.data()
                let sha = data["sha256"] as? String ?? ""
                let bytes = Self.int64Value(data["bytes"]) ?? -1
                let deleted = (data["deleted"] as? Bool) ?? false
                remote[d.documentID] = (sha, bytes, deleted)
            }
            for clip in prepared {
                if let r = remote[clip.id],
                   r.deleted == false,
                   r.sha == clip.sha256,
                   r.bytes == clip.bytes {
                    continue // already up to date
                }
                toUpload.append(clip)
            }
        } catch {
            // If snapshot read fails now, upload all prepared
            toUpload = prepared
        }

        // --- 4) Upload loop (parallel, capped)
        let totalWork = toUpload.count
        print("ℹ️ Initial backup: toUpload=\(totalWork) / prepared=\(prepared.count)")

        guard totalWork > 0 else {
            print("✅ Initial backup: nothing to upload after preflight.")
            publish(.init(state: .finishing, total: 0, done: 0, currentName: nil))
            publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
            return
        }

        // now announce uploading
        publish(.init(state: .uploading, total: totalWork, done: 0, currentName: nil))


        let gate = Gate(maxParallelUploads)
        var done = 0
        var succeeded = 0

        await withTaskGroup(of: Void.self) { group in
            for clip in toUpload {
                group.addTask {
                    await gate.acquire()
                    defer { Task { await gate.release() } }

                    let shouldStop = await MainActor.run { self.isShuttingDown || self.activeBackupId != backupId }
                    if shouldStop || Task.isCancelled { return }

                    print("⬆️  Upload starting: \(clip.id).\(clip.ext) (\(clip.bytes) bytes)")

                    do {
                        try await self.uploadIfNeeded(clip)
                        print("✅ Upload finished: \(clip.id).\(clip.ext)")
                        await MainActor.run { succeeded += 1 }
                    } catch {
                        print("❌ Upload failed for \(clip.id): \(error.localizedDescription)")
                    }

                    await MainActor.run {
                        done += 1
                        self.publish(.init(state: .uploading, total: totalWork, done: done, currentName: clip.id))
                    }
                }
            }
            await group.waitForAll()
        }

         if isShuttingDown || self.activeBackupId != backupId || Task.isCancelled {
             publish(.init(state: .idle, total: succeeded, done: succeeded, currentName: nil))
             print("ℹ️ Initial backup aborted: uploaded \(succeeded) before stop.")
             return
         }

        // Flush any queued metadata writes before finishing
        await metadataWriter?.flushNow()
        if succeeded > 0 {
            await touchBackup(backupId)
        }
        publish(.init(state: .finishing, total: succeeded, done: succeeded, currentName: nil))
        publish(.init(state: .idle, total: succeeded, done: succeeded, currentName: nil))
        print("✅ Initial backup complete. Uploaded \(succeeded) / \(totalWork).")
    }


    // MARK: - Upload + metadata
    private func uploadIfNeeded(_ clip: LocalClip) async throws {
        guard !isShuttingDown, let backupId = self.activeBackupId else {
            throw BackupError.storageUploadFailed   // or .aborted if you add it
        }
        let coll = try self.clipsCollection(backupId)
        let docRef = coll.document(clip.id)

        // Check existing metadata
        let existing = try await docRef.getDocument()
        if let data = existing.data(),
           let remoteSha = data["sha256"] as? String,
           let remoteBytes = Self.int64Value(data["bytes"]),
           remoteSha == clip.sha256,
           remoteBytes == clip.bytes,
           (data["deleted"] as? Bool) != true {
            // Already up-to-date
            return
        }

        // Upload to Storage
        let bucket = try self.clipsBucket(backupId)
        let objectRef = bucket.child("\(clip.id).\(clip.ext)")
        let metadata = StorageMetadata()
        metadata.contentType = mimeType(for: clip.ext)

        try await putFile(from: clip.fileURL, to: objectRef, metadata: metadata)

        // Write Firestore metadata (upsert)
        let doc: [String: Any] = [
            "path": objectRef.fullPath,
            "bytes": clip.bytes,
            "sha256": clip.sha256,
            "createdAt": Timestamp(date: clip.createdAt),
            "journalId": clip.journalId as Any,
            "ext": clip.ext,
            "deleted": false
        ]
        await metadataWriter?.enqueue(id: clip.id, doc: doc)
    }

    private func putFile(from url: URL,
                         to ref: StorageReference,
                         metadata: StorageMetadata?) async throws {
        // If the file doesn’t exist locally, bail
        guard FileManager.default.fileExists(atPath: url.path) else {
            throw BackupError.missingFile
        }

        return try await withCheckedThrowingContinuation { cont in
            var task: StorageUploadTask? = nil

            task = ref.putFile(from: url, metadata: metadata) { _, error in
                // remove from tracking
                if let t = task {
                    self.uploadTasks.removeAll { $0 === t }
                }

                if let error {
                    cont.resume(throwing: error)
                } else {
                    cont.resume(returning: ())
                }
            }

            // keep a handle so we can cancel on sign-out / toggle OFF
            if let t = task {
                self.uploadTasks.append(t)

                // Optional: progress logging
                t.observe(.progress) { snap in
                    guard let p = snap.progress else { return }
                    guard p.totalUnitCount > 0 else { return }
                    let ratio = Double(p.completedUnitCount) / Double(p.totalUnitCount)
                    // Guard against NaN/Infinity which crashes Int() conversion
                    guard ratio.isFinite else { return }
                    let pct = Int(ratio * 100)
                    print("Upload \(ref.name): \(pct)% (\(p.completedUnitCount)/\(p.totalUnitCount) bytes)")
                }

                // Only log failures here; do not resume the continuation again
                t.observe(.failure) { snap in
                    if let e = snap.error {
                        print("❌ Storage failure \(ref.fullPath): \(e.localizedDescription)")
                    }
                }
            }
        }
    }


    private nonisolated func prepareLocalClip(id: String, url: URL, createdAt: Date, journalId: String?, ext: String) async throws -> LocalClip {
        let attrs = try FileManager.default.attributesOfItem(atPath: url.path)
        let bytes = (attrs[.size] as? NSNumber)?.int64Value ?? 0
        let mtime = (attrs[.modificationDate] as? Date)?.timeIntervalSince1970 ?? 0
        let key = HashKey(path: url.path, size: bytes, mtime: mtime)

        let hash: String
        if let cached = await hashCache.value(for: key) {
            hash = cached
        } else {
            let h = try sha256(forFileAt: url)
            await hashCache.store(h, for: key)
            hash = h
        }

        return LocalClip(id: id,
                         fileURL: url,
                         bytes: bytes,
                         sha256: hash,
                         createdAt: createdAt,
                         journalId: journalId,
                         ext: ext)
    }


    /// Call when a brand-new local clip is saved.
    func onLocalClipAdded(id: String, fileURL: URL, createdAt: Date, journalId: String?, ext: String) {
        Task {
            guard uid != nil else { return }
            guard self.activeBackupId != nil else { return } // backup is OFF → no-op
            do {
                try await worker.run {
                    // BEFORE you prepare/upload:
                    self.publish(.init(state: .uploading, total: 1, done: 0, currentName: id))

                    let clip = try await self.prepareLocalClip(id: id, url: fileURL, createdAt: createdAt, journalId: journalId, ext: ext)
                    try await self.uploadIfNeeded(clip)
                    if let backupId = self.activeBackupId {
                        await self.touchBackup(backupId)
                    }

                    // AFTER success:
                    self.publish(.init(state: .finishing, total: 1, done: 1, currentName: id))
                    self.publish(.init(state: .idle, total: 1, done: 1, currentName: nil))
                }
            } catch {
                // (keep your existing print)
                self.publish(.init(state: .error, total: 1, done: 0, currentName: id))
            }

        }
    }


    /// Call when a local clip is deleted (immediate blob delete + tombstone doc).
    /// Call when a local clip is deleted (immediate blob delete + tombstone doc) for the ACTIVE backup.
    func onLocalClipDeleted(id: String, ext: String?) {
        Task {
            guard uid != nil else { return }
            guard let backupId = self.activeBackupId else { return } // backup is OFF → no-op
            do {
                try await worker.run {
                    // 1) Read doc to get authoritative storage path (best-effort)
                    let coll   = try self.clipsCollection(backupId)
                    let docRef = coll.document(id)

                    var storageRefToDelete: StorageReference? = nil
                    do {
                        let snap = try await docRef.getDocument()
                        if let data = snap.data(), let path = data["path"] as? String, !path.isEmpty {
                            storageRefToDelete = self.storage.reference(withPath: path)
                        }
                    } catch {
                        // Firestore read can fail (offline); we'll fall back below.
                        print("ℹ️ onLocalClipDeleted: could not read doc for \(id): \(error.localizedDescription)")
                    }

                    // 2) Fallbacks if no path on the doc → use the backup-scoped bucket
                    if storageRefToDelete == nil {
                        let bucket = try self.clipsBucket(backupId)
                        if let ext {
                            storageRefToDelete = bucket.child("\(id).\(ext)")
                        } else {
                            // Final safety: try common extensions until one deletes
                            let candidates = ["mov","mp4","m4v","jpg","jpeg","png","heic"]
                            for e in candidates {
                                let ref = bucket.child("\(id).\(e)")
                                do { try await ref.delete(); storageRefToDelete = ref; break } catch { /* keep trying */ }
                            }
                        }
                    }

                    // 3) Delete the storage object (if we resolved any path)
                    if let objectRef = storageRefToDelete {
                        do { try await objectRef.delete() }
                        catch { print("⚠️ Storage delete failed for \(id): \(error.localizedDescription)") }
                    } else {
                        print("⚠️ No storage path resolved for \(id); blob may already be gone.")
                    }

                    // 4) Tombstone the Firestore doc (and record deletedAt)
                    try await docRef.setData([
                        "deleted": true,
                        "deletedAt": FieldValue.serverTimestamp()
                    ], merge: true)
                    await self.touchBackup(backupId)
                }
            } catch {
                print("❌ Incremental delete failed for \(id): \(error)")
            }
        }
    }
}


enum BackupError: Error {
    case missingUser
    case missingFile
    case unsupportedType
    case firestoreWriteFailed
    case storageUploadFailed
}

private func mimeType(for ext: String) -> String {
    switch ext.lowercased() {
    case "mp4", "m4v": return "video/mp4"
    case "mov":        return "video/quicktime"
    case "jpg", "jpeg":return "image/jpeg"
    case "png":        return "image/png"
    case "heic":       return "image/heic"
    default:           return "application/octet-stream"
    }
}

// MARK: - SHA256
private func sha256(forFileAt url: URL) throws -> String {
    let handle = try FileHandle(forReadingFrom: url)
    defer { try? handle.close() }

    var hasher = SHA256()
    while autoreleasepool(invoking: {
        let data = try? handle.read(upToCount: 1_048_576) // 1 MB chunks
        if let data, !data.isEmpty {
            hasher.update(data: data)
            return true
        }
        return false
    }) {}
    let digest = hasher.finalize()
    return digest.map { String(format: "%02x", $0) }.joined()
}


// MARK: - Types (keep small & transport-friendly)

struct LocalClip {
    let id: String           // stable local id
    let fileURL: URL         // local path to media
    let bytes: Int64
    let sha256: String       // we’ll compute in Step 2
    let createdAt: Date
    let journalId: String?   // project/journal foreign key
    let ext: String          // "mov", "mp4", "jpg", etc.
}

struct RemoteClip: Codable {
    let path: String         // storage path "users/{uid}/clips/{clipId}.ext"
    let bytes: Int64
    let sha256: String
    let createdAt: Date
    let journalId: String?
    let ext: String
    let deleted: Bool        // tombstone
}
