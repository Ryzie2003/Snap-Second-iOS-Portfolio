    func syncActiveJournalSnapshotIfNeeded() async {
        guard isSignedIn, let backupId = activeBackupId, let snapshot = journalSnapshotProvider else {
            return
        }

        do {
            let journals = snapshot()
            let jcol = try journalsCollection(backupId)
            let existing = try await jcol.getDocuments()
            let existingIDs = Set(existing.documents.map(\.documentID))
            let currentIDs = Set(journals.map(\.id))

            if !journals.isEmpty || !existingIDs.isEmpty {
                let batch = db.batch()
                for journal in journals {
                    batch.setData(
                        journalDocumentData(for: journal),
                        forDocument: jcol.document(journal.id),
                        merge: true
                    )
                }
                for staleID in existingIDs.subtracting(currentIDs) {
                    batch.deleteDocument(jcol.document(staleID))
                }
                try await batch.commit()
            }

            await touchBackup(backupId)
        } catch {
            print("⚠️ Failed to sync journals for backup \(backupId): \(error.localizedDescription)")
        }
    }

    static func mergeBackupJournals(remoteJournals: [BackupJournal],
                                    clipReferences: [RestoreJournalReference],
                                    fallbackJournals: [BackupJournal]) -> [BackupJournal] {
        var merged = Dictionary(uniqueKeysWithValues: remoteJournals.map { ($0.id, $0) })
        let fallbackByID = Dictionary(uniqueKeysWithValues: fallbackJournals.map { ($0.id, $0) })
        let maxKnownSortIndex = (remoteJournals.map(\.sortIndex) + fallbackJournals.map(\.sortIndex)).max() ?? -1
        var nextSortIndex = maxKnownSortIndex
        var placeholderOrdinal = 1

        var referencesByID: [String: RestoreJournalReference] = [:]
        for ref in clipReferences {
            if let existing = referencesByID[ref.id] {
                referencesByID[ref.id] = RestoreJournalReference(
                    id: ref.id,
                    name: existing.name ?? ref.name,
                    createdAt: existing.createdAt ?? ref.createdAt,
                    type: existing.type ?? ref.type,
                    sortIndex: existing.sortIndex ?? ref.sortIndex
                )
            } else {
                referencesByID[ref.id] = ref
            }
        }

        for ref in referencesByID.values.sorted(by: { $0.id < $1.id }) {
            guard merged[ref.id] == nil else { continue }

            if let fallback = fallbackByID[ref.id] {
                merged[ref.id] = BackupJournal(
                    id: fallback.id,
                    name: Self.normalizedJournalName(ref.name, fallback: fallback.name),
                    createdAt: ref.createdAt ?? fallback.createdAt,
                    type: ref.type.map { Self.normalizedJournalType($0) } ?? fallback.type,
                    sortIndex: ref.sortIndex ?? fallback.sortIndex
                )
                continue
            }

            nextSortIndex += 1
            let placeholderName = Self.normalizedJournalName(
                ref.name,
                fallback: "Restored Journal \(placeholderOrdinal)"
            )
            placeholderOrdinal += 1

            merged[ref.id] = BackupJournal(
                id: ref.id,
                name: placeholderName,
                createdAt: ref.createdAt ?? Date(timeIntervalSince1970: 0),
                type: ref.type.map { Self.normalizedJournalType($0) } ?? "dailyJournal",
                sortIndex: ref.sortIndex ?? nextSortIndex
            )
        }

        return merged.values.sorted {
            if $0.sortIndex != $1.sortIndex { return $0.sortIndex < $1.sortIndex }
            if $0.createdAt != $1.createdAt { return $0.createdAt < $1.createdAt }
            return $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending
        }
    }



