// Throttle parallel tasks
actor Gate {
    private var permits: Int
    init(_ n: Int) { permits = n }
    func acquire() async {
        while permits == 0 { await Task.yield() }
        permits -= 1
    }
    func release() async { permits += 1 }
}

actor Counter {
    private var value = 0
    func inc() -> Int { value += 1; return value }
}

actor FirestoreMetadataWriter {
    private let db = Firestore.firestore()
    private let col: CollectionReference
    private var pending: [[String: Any]] = []
    private var pendingIds: [String] = []
    private var flushScheduled = false
    private let batchSize = 200
    private let debounceMs: UInt64 = 400

    init(collection: CollectionReference) {
        self.col = collection
    }

    func enqueue(id: String, doc: [String: Any]) {
        pending.append(doc)
        pendingIds.append(id)
        if pending.count >= batchSize {
            Task { await flushNow() }
        } else if !flushScheduled {
            flushScheduled = true
            Task {
                try? await Task.sleep(nanoseconds: debounceMs * 1_000_000)
                await flushNow()
            }
        }
    }

    private func shouldRetry(_ err: Error) -> Bool {
        let ns = err as NSError
        // App Check / permission / transient
        return ns.domain == FirestoreErrorDomain
            || ns.code == 7 /* PERMISSION_DENIED */
            || ns.code == 14 /* UNAVAILABLE */
            || ns.code == 4  /* DEADLINE_EXCEEDED */
    }

    private func backoff(_ attempt: Int) async {
        let baseMs = 250
        let capMs  = 4000
        let delay  = min(capMs, baseMs << attempt)
        try? await Task.sleep(nanoseconds: UInt64(delay) * 1_000_000)
    }

    private func takeBatch() -> (ids: [String], docs: [[String: Any]]) {
        let n = min(batchSize, pending.count)
        let docs = Array(pending.prefix(n))
        let ids  = Array(pendingIds.prefix(n))
        pending.removeFirst(n)
        pendingIds.removeFirst(n)
        return (ids, docs)
    }

    private func putBack(ids: [String], docs: [[String: Any]]) {
        pending = docs + pending
        pendingIds = ids + pendingIds
    }

    private func hasWork() -> Bool { !pending.isEmpty }

    func flushNow() async {
        flushScheduled = false
        guard hasWork() else { return }

        var attempt = 0
        while hasWork() {
            let (ids, docs) = takeBatch()
            do {
                let batch = db.batch()
                for (i, d) in docs.enumerated() {
                    let id = ids[i]
                    let docRef = col.document(id)
                    batch.setData(d, forDocument: docRef, merge: true)
                }
                try await batch.commit()
            } catch {
                // Retry on AppCheck/permission/transient
                if shouldRetry(error) && attempt < 5 {
                    attempt += 1
                    await backoff(attempt)
                    // Put the batch back and try again
                    putBack(ids: ids, docs: docs)
                } else {
                    print("❌ Firestore batch commit failed: \(error.localizedDescription)")
                }
            }
        }
    }
}




