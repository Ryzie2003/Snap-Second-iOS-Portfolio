    public func listBackups(for uid: String) async throws -> [BackupSummary] {
        let col = db.collection("users").document(uid).collection("backups")
        let snap = try await col.getDocuments(source: .server)

        var results: [BackupSummary] = []
        results.reserveCapacity(snap.documents.count)

        for d in snap.documents {
            let data = d.data()
            let name = (data["name"] as? String) ?? d.documentID
            let status = (data["status"] as? String) ?? "unknown"
            let deviceName = data["deviceName"] as? String
            let createdAt: Date = (data["createdAt"] as? Timestamp)?.dateValue() ?? Date(timeIntervalSince1970: 0)
            let updatedAt: Date? = (data["updatedAt"] as? Timestamp)?.dateValue()

            let clipsQuery = d.reference.collection("clips").whereField("deleted", isEqualTo: false)
            let agg = try await clipsQuery.count.getAggregation(source: .server)
            let clipCount = Int(truncating: agg.count)

            results.append(BackupSummary(
                id: d.documentID,
                name: name,
                status: status,
                createdAt: createdAt,
                updatedAt: updatedAt,
                deviceName: deviceName,
                clipCount: clipCount
            ))
        }

        results.sort { lhs, rhs in
            lhs.displayDate > rhs.displayDate
        }
        return results
    }


    public enum RestoreMode { case missingOnly, overwriteAll }

    public func restoreBackup(backupId: String, mode: RestoreMode = .missingOnly) async {
        // In case backup was OFF and uid was cleared, reattach from Firebase now.
        if self.uid == nil, let u = Auth.auth().currentUser, !u.isAnonymous { self.uid = u.uid }

        guard isSignedIn, let probe = restoreProbe, let commit = restoreCommit else {
            print("ℹ️ restoreBackup: blocked (not signed in or handlers missing)")
            publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
            return
        }

        publish(.init(state: .restoring, total: 0, done: 0, currentName: nil))

        do {
            // 1) Fetch remote clip docs in one round-trip
            let coll = try clipsCollection(backupId)
            let snap = try await coll.getDocuments()
            struct Remote: Hashable {
                let id: String
                let ext: String
                let sha: String
                let bytes: Int64
                let createdAt: Date
                let journalId: String?
                let journalName: String?
                let journalCreatedAt: Date?
                let journalType: String?
                let journalSortIndex: Int?
            }
            var remote: [Remote] = []
            remote.reserveCapacity(snap.documents.count)

            for d in snap.documents {
                let data = d.data()
                guard
                    let sha = data["sha256"] as? String,
                    let bytes = Self.int64Value(data["bytes"]),
                    let ext = data["ext"] as? String,
                    let created = (data["createdAt"] as? Timestamp)?.dateValue()
                else { continue }
                let id = d.documentID
                let jid = data["journalId"] as? String
                let journalName = data["journalName"] as? String
                let journalCreatedAt = (data["journalCreatedAt"] as? Timestamp)?.dateValue()
                let journalType = data["journalType"] as? String
                let journalSortIndex = Self.intValue(data["journalSortIndex"])
                let deleted = (data["deleted"] as? Bool) ?? false
                if !deleted {
                    remote.append(.init(
                        id: id,
                        ext: ext,
                        sha: sha,
                        bytes: bytes,
                        createdAt: created,
                        journalId: jid,
                        journalName: journalName,
                        journalCreatedAt: journalCreatedAt,
                        journalType: journalType,
                        journalSortIndex: journalSortIndex
                    ))
                }
            }

            // 2) Rebuild journals before restoring any clips.
            if mode == .overwriteAll, let rebuild = journalRebuilder {
                let jcol = try journalsCollection(backupId)
                let jsnap = try await jcol.getDocuments()
                var remoteJournals: [BackupJournal] = []
                remoteJournals.reserveCapacity(jsnap.documents.count)
                for (index, d) in jsnap.documents.enumerated() {
                    remoteJournals.append(
                        decodeJournal(
                            documentID: d.documentID,
                            data: d.data(),
                            fallbackSortIndex: index
                        )
                    )
                }

                let clipJournalRefs = remote.compactMap { clip -> RestoreJournalReference? in
                    guard let journalId = clip.journalId else { return nil }
                    return RestoreJournalReference(
                        id: journalId,
                        name: clip.journalName,
                        createdAt: clip.journalCreatedAt,
                        type: clip.journalType,
                        sortIndex: clip.journalSortIndex
                    )
                }

                let localFallbacks = journalSnapshotProvider?() ?? []
                let journals = Self.mergeBackupJournals(
                    remoteJournals: remoteJournals,
                    clipReferences: clipJournalRefs,
                    fallbackJournals: localFallbacks
                )

                if remoteJournals.count < Set(clipJournalRefs.map(\.id)).count {
                    print("⚠️ Restore recovered missing journal metadata from clip references/local fallback.")
                }

                await rebuild(journals)
            }

            // 3) Decide which need restore
            var toRestore: [Remote] = []
            toRestore.reserveCapacity(remote.count)
            for r in remote {
                if mode == .overwriteAll {
                    toRestore.append(r)
                    continue
                }
                // missingOnly: if local exists and hash matches, ensure metadata, then skip download
                if let url = probe(r.id, r.ext),
                   let attrs = try? FileManager.default.attributesOfItem(atPath: url.path),
                   let size = (attrs[.size] as? NSNumber)?.int64Value,
                   let localSha = try? sha256(forFileAt: url),
                   size == r.bytes, localSha == r.sha {
                    do {
                        try commit(r.id, url, r.createdAt, r.journalId, r.ext) // <-- re-create DB record
                    } catch {
                        print("⚠️ restore ensure-meta failed for \(r.id): \(error.localizedDescription)")
                        // Optional: fall back to download if commit requires temp files
                        // toRestore.append(r)
                    }
                    continue
                }
                toRestore.append(r)
            }

            // 4) Download in parallel (capped)
            let total = toRestore.count
            publish(.init(state: .restoring, total: total, done: 0, currentName: nil))
            guard total > 0 else {
                publish(.init(state: .finishing, total: 0, done: 0, currentName: nil))
                publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
                print("✅ Restore: nothing to do; local library already matches backup.")
                return
            }

            let gate = Gate(maxParallelUploads)    // reuse your Gate (3–4 is fine for downloads too)
            let counter = Counter()
            let bucket = try self.clipsBucket(backupId)  // Storage folder ref

            await withTaskGroup(of: Void.self) { group in
                for r in toRestore {
                    group.addTask {
                        await gate.acquire()
                        defer { Task { await gate.release() } }

                        let ref = bucket.child("\(r.id).\(r.ext)")
                        // download to a temp file
                        let tmp = URL(fileURLWithPath: NSTemporaryDirectory()).appendingPathComponent("\(r.id).\(r.ext)")
                        do {
                            try? FileManager.default.removeItem(at: tmp)
                            try await self.download(to: tmp, from: ref)
                            // verify
                            let sha = try sha256(forFileAt: tmp)
                            let attrs = try FileManager.default.attributesOfItem(atPath: tmp.path)
                            let bytes = (attrs[.size] as? NSNumber)?.int64Value ?? -1
                            guard sha == r.sha, bytes == r.bytes else {
                                throw NSError(domain: "Restore", code: -1, userInfo: [NSLocalizedDescriptionKey: "Hash/size mismatch for \(r.id)"])
                            }
                            // hand back to app (moves to library + DB)
                            try commit(r.id, tmp, r.createdAt, r.journalId, r.ext)
                        } catch {
                            print("❌ Restore failed for \(r.id): \(error.localizedDescription)")
                        }

                        let done = await counter.inc()
                        await MainActor.run {
                            self.publish(.init(state: .restoring, total: total, done: done, currentName: r.id))
                        }
                    }
                }
                await group.waitForAll()
            }

            publish(.init(state: .finishing, total: 0, done: 0, currentName: nil))
            publish(.init(state: .idle, total: 0, done: 0, currentName: nil))
            print("✅ Restore complete (\(toRestore.count) items)")
        } catch {
            print("❌ restoreBackup error:", error.localizedDescription)
            publish(.init(state: .error, total: 0, done: 0, currentName: nil))
        }
    }


    private func download(to url: URL, from ref: StorageReference) async throws {
        try await withCheckedThrowingContinuation { (cont: CheckedContinuation<Void, Error>) in
            let task = ref.write(toFile: url) { _, error in
                if let error { cont.resume(throwing: error) } else { cont.resume(returning: ()) }
            }
            // (optional) observe
            task.observe(.failure) { snap in
                if let e = snap.error { print("❌ download failure \(ref.fullPath): \(e.localizedDescription)") }
            }
        }
    }




