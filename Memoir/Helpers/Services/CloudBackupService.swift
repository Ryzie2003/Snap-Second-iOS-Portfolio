    func enableBackup(for uid: String) async throws {
        self.uid = uid

        // Restore last active session if present and still active
        if let savedId = defaults.string(forKey: activeIdKey) {
            do {
                let doc = try await backupDoc(savedId).getDocument()
                if (doc.data()?["status"] as? String) == "active" {
                    self.activeBackupId = savedId
                    // ⬇️ initialize metadata writer for incremental events
                    let col = try self.clipsCollection(savedId)
                    self.metadataWriter = FirestoreMetadataWriter(collection: col)
                    await self.syncActiveJournalSnapshotIfNeeded()

                    // ⬇️ auto-resume the initial full upload of any remaining clips
                    publish(.init(state: .scanning, total: 0, done: 0, currentName: nil))
                    startInitialBackup(forceRestart: false)
                } else {
                    defaults.removeObject(forKey: activeIdKey)
                }
            } catch {
                // If we can’t read, don’t crash; just clear stale state
                defaults.removeObject(forKey: activeIdKey)
            }
        }


    }


